import { boot, loadPlan } from "./lib/app.mjs";
const WAIT=Number(process.env.WAIT||0);
const { browser, page } = await boot();
await loadPlan(page, { nodes: [], drawers: [], wires: [] });
await page.waitForTimeout(300);
const rect = () => page.evaluate(() => { const r = document.querySelector(".sn").getBoundingClientRect(); return { x: r.x, y: r.y, w: r.width, h: r.height, zoom: window.__ccStore && 0 }; });
await page.mouse.click(700, 500, { button: "right" });
await page.waitForTimeout(300);
await page.getByText(/Add a sticky note/i).first().click();
await page.waitForTimeout(600);
const stor = () => page.evaluate(() => { const a = window.__ccStore.getState().project.annotations[0]; return a.position; });
console.log("start", JSON.stringify(await stor()), JSON.stringify(await rect()));
async function drag(label, dx, dy, steps) {
  const b = await rect();
  const s0 = await stor();
  await page.mouse.move(b.x + b.w / 2, b.y + b.h / 2);
  await page.mouse.down();
  await page.mouse.move(b.x + b.w / 2 + dx, b.y + b.h / 2 + dy, { steps });
  const live = await rect();
  await page.waitForTimeout(WAIT);
  await page.mouse.up();
  await page.waitForTimeout(300);
  const s1 = await stor();
  const a = await rect();
  console.log(label, dx, dy, "store", s1.x - s0.x, s1.y - s0.y, "rect", a.x - b.x, a.y - b.y, "live", live.x - b.x, live.y - b.y, "zoom", await page.evaluate(()=>getComputedStyle(document.querySelector(".react-flow__viewport")).transform));
}
await page.keyboard.press("Escape");
await drag("idle", 60, 30, 5);
await drag("idle", 100, 0, 10);
await page.mouse.click((await rect()).x + 90, (await rect()).y + 60);
await page.keyboard.type("hello");
await drag("writing", 60, 30, 5);
await drag("writing", 100, 0, 10);
await drag("writing", 7, 0, 3);
await browser.close();
